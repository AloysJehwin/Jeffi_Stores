import 'server-only'
import fs from 'node:fs'
import path from 'node:path'
import { PassThrough } from 'node:stream'
import { displayText } from '../format'
import type { ExportColumn } from '../types'
import type { ExportRow } from '../define'
import { alignOf, generatedAtText, makeTotals, totalsLabelKey, truncationNote, toWeb, type ExportDocument, type Rendered, CONTENT_TYPES } from './common'

// PDF via PDFKit: a letterhead on the first page (logo, store, GSTIN, address, title, period,
// filters), a running title on later pages, tables whose header repeats on every page, a totals row,
// and a footer with "generated by" and "Page n of N". Noto Sans carries the ₹ sign.

const PDFDocument = eval('require')('pdfkit')

const M = 36
const FONT_DIRS = ['packages/store-core/assets/fonts', '../packages/store-core/assets/fonts', '../../packages/store-core/assets/fonts']
const INK = '#0f172a'
const MUTED = '#64748b'
const HEAD_BG = '#1e293b'
const ZEBRA = '#f8fafc'
const LINE = '#cbd5e1'
const ACCENT = '#4f46e5'

function fontDir(): string | null {
  for (const d of FONT_DIRS) {
    const p = path.resolve(process.cwd(), d)
    if (fs.existsSync(path.join(p, 'NotoSans-Regular.ttf'))) return p
  }
  return null
}

type Doc = any

export async function renderPdf(doc: ExportDocument, run: <T>(fn: () => Promise<T>) => Promise<T>): Promise<Rendered> {
  const widest = Math.max(...doc.sections.map(s => s.columns.reduce((n, c) => n + (c.width ?? 1), 0)), 1)
  const pdf: Doc = new PDFDocument({
    size: 'A4',
    layout: widest > 6.5 ? 'landscape' : 'portrait',
    margins: { top: M, bottom: M + 14, left: M, right: M },
    bufferPages: true,
    info: { Title: doc.title, Author: doc.brand?.name || '', Creator: doc.generatedBy },
  })
  const dir = fontDir()
  let body = 'Helvetica'
  let bold = 'Helvetica-Bold'
  let rupee = true
  if (dir) {
    pdf.registerFont('Body', path.join(dir, 'NotoSans-Regular.ttf'))
    pdf.registerFont('Bold', path.join(dir, 'NotoSans-Bold.ttf'))
    body = 'Body'
    bold = 'Bold'
  } else rupee = false
  const text = (v: unknown, c: Pick<ExportColumn, 'type'>) => {
    const s = displayText(v, c.type)
    return rupee ? s : s.replace(/₹/g, 'Rs.')
  }

  const out = new PassThrough()
  pdf.pipe(out)
  const W = () => pdf.page.width - M * 2
  const bottom = () => pdf.page.height - pdf.page.margins.bottom
  const b = doc.branding

  function letterhead() {
    if (!b.header) {
      pdf.y = M
      return
    }
    let x = M
    const top = M
    let h = 0
    if (b.logo && doc.brand?.logo) {
      try {
        pdf.image(doc.brand.logo, M, top, { fit: [64, 40] })
        x = M + 74
        h = 40
      } catch {
        /* unreadable logo: name only */
      }
    }
    const right = W() * 0.42
    const leftW = W() - (x - M) - right - 8
    let y = top
    if (b.storeName && doc.brand?.name) {
      pdf.font(bold).fontSize(13).fillColor(INK).text(doc.brand.name, x, y, { width: leftW })
      y = pdf.y
    }
    pdf.font(body).fontSize(8).fillColor(MUTED)
    if (b.storeName && doc.brand?.legalName && doc.brand.legalName !== doc.brand.name) {
      pdf.text(doc.brand.legalName, x, y, { width: leftW })
      y = pdf.y
    }
    if (b.gstin && doc.brand?.gstin) {
      pdf.text(`GSTIN: ${doc.brand.gstin}`, x, y, { width: leftW })
      y = pdf.y
    }
    if (b.address && doc.brand?.address) {
      pdf.text(doc.brand.address, x, y, { width: leftW })
      y = pdf.y
    }
    let ry = top
    const rx = M + W() - right
    if (b.title) {
      pdf.font(bold).fontSize(15).fillColor(INK).text(doc.title, rx, ry, { width: right, align: 'right' })
      ry = pdf.y
    }
    pdf.font(body).fontSize(8).fillColor(MUTED)
    if (b.period && doc.period) {
      pdf.text(doc.period, rx, ry, { width: right, align: 'right' })
      ry = pdf.y
    }
    if (b.generatedAt) {
      pdf.text(`Generated ${generatedAtText(doc.generatedAt)}`, rx, ry, { width: right, align: 'right' })
      ry = pdf.y
    }
    y = Math.max(y, ry, top + h) + 6
    if (b.filters) {
      pdf.font(body).fontSize(7.5).fillColor(MUTED).text(`Filters: ${doc.filters.length ? doc.filters.join(' · ') : 'None'}`, M, y, { width: W() })
      y = pdf.y + 4
    }
    pdf.moveTo(M, y).lineTo(M + W(), y).lineWidth(1).strokeColor(ACCENT).stroke()
    pdf.y = y + 10
  }

  function runningHead() {
    pdf.font(body).fontSize(7.5).fillColor(MUTED).text([doc.title, b.storeName ? doc.brand?.name : ''].filter(Boolean).join(' · '), M, M - 14, { width: W(), lineBreak: false })
    pdf.y = M + 4
  }

  function newPage() {
    pdf.addPage()
    if (b.header) runningHead()
    else pdf.y = M
  }

  function widths(cols: ExportColumn[]): number[] {
    const total = cols.reduce((n, c) => n + (c.width ?? 1), 0) || 1
    return cols.map(c => ((c.width ?? 1) / total) * W())
  }

  const FS = 7.5
  const PAD = 3
  const MAX_LINES = 3

  function rowHeight(cells: string[], ws: number[], font: string): number {
    pdf.font(font).fontSize(FS)
    const line = pdf.currentLineHeight(true)
    let h = line
    cells.forEach((s, i) => {
      if (!s) return
      h = Math.max(h, Math.min(pdf.heightOfString(s, { width: ws[i] - PAD * 2 }), line * MAX_LINES))
    })
    return h + PAD * 2
  }

  function drawRow(cols: ExportColumn[], cells: string[], ws: number[], opts: { font: string; color: string; fill?: string; topRule?: boolean }) {
    const h = rowHeight(cells, ws, opts.font)
    if (pdf.y + h > bottom()) return false
    const y = pdf.y
    if (opts.fill) pdf.rect(M, y, W(), h).fill(opts.fill)
    if (opts.topRule) pdf.moveTo(M, y).lineTo(M + W(), y).lineWidth(0.8).strokeColor(MUTED).stroke()
    let x = M
    pdf.font(opts.font).fontSize(FS).fillColor(opts.color)
    cells.forEach((s, i) => {
      pdf.text(s, x + PAD, y + PAD, { width: ws[i] - PAD * 2, height: h - PAD * 2, ellipsis: true, align: alignOf(cols[i].type) })
      x += ws[i]
    })
    pdf.y = y + h
    return true
  }

  function header(cols: ExportColumn[], ws: number[]) {
    if (!drawRow(cols, cols.map(c => c.label), ws, { font: bold, color: '#ffffff', fill: HEAD_BG })) {
      newPage()
      drawRow(cols, cols.map(c => c.label), ws, { font: bold, color: '#ffffff', fill: HEAD_BG })
    }
  }

  function bodyRow(cols: ExportColumn[], r: ExportRow, ws: number[], zebra: boolean) {
    const cells = cols.map(c => text(r[c.key], c))
    const style = { font: body, color: INK, fill: zebra ? ZEBRA : undefined }
    if (!drawRow(cols, cells, ws, style)) {
      newPage()
      header(cols, ws)
      drawRow(cols, cells, ws, style)
    }
  }

  function ensure(h: number) {
    if (pdf.y + h > bottom()) newPage()
  }

  const write = async () => {
    letterhead()
    for (const [i, s] of doc.sections.entries()) {
      const ws = widths(s.columns)
      if (s.title && (doc.sections.length > 1 || i > 0)) {
        ensure(40)
        pdf.font(bold).fontSize(10.5).fillColor(INK).text(s.title, M, pdf.y + (i > 0 ? 8 : 0), { width: W() })
        pdf.y += 4
      }
      header(s.columns, ws)
      const totals = makeTotals(doc, s)
      let n = 0
      for await (const batch of s.rows) {
        for (const r of batch) {
          totals.add(r)
          bodyRow(s.columns, r, ws, n++ % 2 === 1)
        }
      }
      if (!n) {
        ensure(20)
        pdf.font(body).fontSize(FS).fillColor(MUTED).text('No rows.', M + PAD, pdf.y + PAD)
        pdf.y += 6
      }
      const t = totals.result()
      if (t) {
        const labelKey = totalsLabelKey(s.columns, t)
        const cells = s.columns.map(c => (c.key === labelKey ? 'Total' : text(t[c.key], c)))
        if (!drawRow(s.columns, cells, ws, { font: bold, color: INK, fill: '#eef2ff', topRule: true })) {
          newPage()
          header(s.columns, ws)
          drawRow(s.columns, cells, ws, { font: bold, color: INK, fill: '#eef2ff', topRule: true })
        }
      }
      if (b.summary && s.summary?.length) {
        pdf.y += 8
        for (const m of s.summary) {
          ensure(14)
          const y = pdf.y
          pdf.font(body).fontSize(8).fillColor(MUTED).text(m.label, M, y, { width: W() * 0.4 })
          pdf.font(bold).fontSize(8).fillColor(INK).text(text(m.value, m), M + W() * 0.4, y, { width: W() * 0.3, align: 'right' })
          pdf.y = Math.max(pdf.y, y + 12)
        }
      }
      pdf.y += 10
    }
    const note = truncationNote(doc)
    if (note) {
      ensure(20)
      pdf.font(body).fontSize(8).fillColor('#b45309').text(note, M, pdf.y, { width: W() })
    }

    const range = pdf.bufferedPageRange()
    for (let p = range.start; p < range.start + range.count; p++) {
      pdf.switchToPage(p)
      const keep = pdf.page.margins.bottom
      pdf.page.margins.bottom = 0
      const y = pdf.page.height - M + 2
      pdf.moveTo(M, y - 4).lineTo(M + W(), y - 4).lineWidth(0.5).strokeColor(LINE).stroke()
      pdf.font(body).fontSize(7).fillColor(MUTED)
      if (b.generatedBy) pdf.text(`Generated by ${doc.generatedBy} · ${generatedAtText(doc.generatedAt)}`, M, y, { width: W() * 0.7, lineBreak: false })
      if (b.pageNumbers) pdf.text(`Page ${p - range.start + 1} of ${range.count}`, M + W() * 0.7, y, { width: W() * 0.3, align: 'right', lineBreak: false })
      pdf.page.margins.bottom = keep
    }
    pdf.end()
  }

  run(write).catch(err => {
    console.error('[export/pdf]', err)
    out.destroy(err instanceof Error ? err : new Error(String(err)))
  })
  return { body: await toWeb(out), contentType: CONTENT_TYPES.pdf }
}
