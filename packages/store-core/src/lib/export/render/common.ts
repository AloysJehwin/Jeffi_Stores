import 'server-only'
import type { ExportRow, ExportSection } from '../define'
import type { StoreBrand } from '../branding'
import type { BrandingOptions, ColumnType, ExportColumn, ExportFormat } from '../types'
import { Totals } from '../format'

// What every renderer receives: resolved sections (columns fixed, rows as batches), the letterhead
// and the branding switches. Row caps are applied before rows reach a renderer.

export interface ResolvedSection {
  key: string
  title?: string
  columns: ExportColumn[]
  rows: AsyncIterable<ExportRow[]>
  totals: 'auto' | ExportRow | null
  summary?: ExportSection['summary']
}

export interface ExportDocument {
  title: string
  format: ExportFormat
  branding: BrandingOptions
  brand: StoreBrand | null
  period: string | null
  generatedAt: Date
  generatedBy: string
  filters: string[]
  sections: ResolvedSection[]
  /** Set once a section's rows were cut at the format's cap. */
  truncated: { cap: number } | null
}

export interface Rendered {
  body: ReadableStream<Uint8Array>
  contentType: string
}

export const CONTENT_TYPES: Record<ExportFormat, string> = {
  csv: 'text/csv; charset=utf-8',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  pdf: 'application/pdf',
  pptx: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
}

export const generatedAtText = (d: Date) =>
  d.toLocaleString('en-IN', { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hour12: true, timeZone: 'Asia/Kolkata' }) + ' IST'

/** Label/value lines of the header block, in print order, honouring each switch. */
export function headerLines(doc: ExportDocument): { label: string; value: string }[] {
  const b = doc.branding
  if (!b.header) return []
  const out: { label: string; value: string }[] = []
  const brand = doc.brand
  if (b.storeName && brand?.name) out.push({ label: 'Store', value: brand.legalName && brand.legalName !== brand.name ? `${brand.name} (${brand.legalName})` : brand.name })
  if (b.gstin && brand?.gstin) out.push({ label: 'GSTIN', value: brand.gstin })
  if (b.address && brand?.address) out.push({ label: 'Address', value: brand.address })
  if (b.title) out.push({ label: 'Report', value: doc.title })
  if (b.period && doc.period) out.push({ label: 'Period', value: doc.period })
  if (b.generatedAt) out.push({ label: 'Generated', value: generatedAtText(doc.generatedAt) })
  if (b.generatedBy) out.push({ label: 'Generated by', value: doc.generatedBy })
  if (b.filters) out.push({ label: 'Filters', value: doc.filters.length ? doc.filters.join('; ') : 'None' })
  return out
}

/** The section's totals row (computed while the rows stream past), or null. */
export function makeTotals(doc: ExportDocument, s: ResolvedSection): { add: (r: ExportRow) => void; result: () => ExportRow | null } {
  if (!doc.branding.summary || !s.totals) return { add: () => {}, result: () => null }
  if (s.totals !== 'auto') {
    const given = s.totals
    return { add: () => {}, result: () => given }
  }
  const t = new Totals(s.columns)
  if (!t.any) return { add: () => {}, result: () => null }
  return { add: r => t.add(r), result: () => t.result() }
}

/** The first column that isn't totalled carries the "Total" label. */
export function totalsLabelKey(cols: ExportColumn[], totals: ExportRow): string | null {
  const free = cols.find(c => totals[c.key] == null)
  return free?.key ?? null
}

export const alignOf = (t: ColumnType | undefined): 'left' | 'right' => (t === 'money' || t === 'number' || t === 'int' || t === 'percent' ? 'right' : 'left')

export const truncationNote = (doc: ExportDocument) =>
  doc.truncated ? `Only the first ${doc.truncated.cap.toLocaleString('en-IN')} rows are included. Narrow the filters or pick CSV / Excel for more.` : null

/** Node Readable → web stream for the Response body. */
export async function toWeb(node: import('node:stream').Readable): Promise<ReadableStream<Uint8Array>> {
  const { Readable } = await import('node:stream')
  return Readable.toWeb(node) as unknown as ReadableStream<Uint8Array>
}
