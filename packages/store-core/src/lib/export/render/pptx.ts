import 'server-only'
import { displayText } from '../format'
import type { ExportColumn } from '../types'
import type { ExportRow } from '../define'
import { alignOf, generatedAtText, headerLines, makeTotals, totalsLabelKey, truncationNote, type ExportDocument, type Rendered, CONTENT_TYPES } from './common'

// PowerPoint via pptxgenjs (16:9): a title slide (logo, title, store, period, generated, filters),
// a summary slide (totals and key figures per section), then the tables a dozen rows a slide.

const ROWS_PER_SLIDE = 12
const INK = '0F172A'
const MUTED = '64748B'
const ACCENT = '4F46E5'
const HEAD_BG = '1E293B'

const dataUri = (buf: Buffer) => `data:image/${buf[0] === 0x89 ? 'png' : 'jpeg'};base64,${buf.toString('base64')}`

export async function renderPptx(doc: ExportDocument, run: <T>(fn: () => Promise<T>) => Promise<T>): Promise<Rendered> {
  const mod = await import('pptxgenjs')
  const PptxGenJS = (mod as any).default ?? mod
  const pptx = new PptxGenJS()
  pptx.layout = 'LAYOUT_WIDE'
  pptx.title = doc.title
  pptx.company = doc.brand?.name || ''
  pptx.author = doc.generatedBy
  const b = doc.branding
  const footer = [b.storeName ? doc.brand?.name : '', b.generatedBy ? `Generated by ${doc.generatedBy}` : '', b.generatedAt ? generatedAtText(doc.generatedAt) : ''].filter(Boolean).join('  ·  ')

  const sections = await run(async () => {
    const out: { title: string; columns: ExportColumn[]; rows: ExportRow[]; totals: ExportRow | null; summary: NonNullable<ExportDocument['sections'][number]['summary']> }[] = []
    for (const s of doc.sections) {
      const totals = makeTotals(doc, s)
      const rows: ExportRow[] = []
      for await (const batch of s.rows) {
        for (const r of batch) {
          totals.add(r)
          rows.push(r)
        }
      }
      out.push({ title: s.title || doc.title, columns: s.columns, rows, totals: totals.result(), summary: b.summary ? s.summary ?? [] : [] })
    }
    return out
  })

  if (b.header) {
    const slide = pptx.addSlide()
    slide.background = { color: 'FFFFFF' }
    slide.addShape(pptx.ShapeType.rect, { x: 0, y: 0, w: 0.25, h: 7.5, fill: { color: ACCENT } })
    if (b.logo && doc.brand?.logo) slide.addImage({ data: dataUri(doc.brand.logo), x: 0.8, y: 0.6, w: 1.6, h: 1.0, sizing: { type: 'contain', w: 1.6, h: 1.0 } })
    if (b.title) slide.addText(doc.title, { x: 0.8, y: 2.0, w: 11.5, h: 1.0, fontSize: 36, bold: true, color: INK })
    const lines = headerLines(doc).filter(l => l.label !== 'Report')
    slide.addText(
      lines.map(l => ({ text: `${l.label}: ${l.value}`, options: { breakLine: true } })),
      { x: 0.8, y: 3.2, w: 11.5, h: 3.4, fontSize: 14, color: MUTED, valign: 'top', paraSpaceAfter: 4 }
    )
  }

  const figures = sections.flatMap(s => {
    const items: { label: string; value: string }[] = []
    if (s.totals) for (const c of s.columns) if (s.totals[c.key] != null && c.total) items.push({ label: `${c.label}${sections.length > 1 ? ` (${s.title})` : ''}`, value: displayText(s.totals[c.key], c.type) })
    for (const m of s.summary) items.push({ label: m.label, value: displayText(m.value, m.type) })
    if (!items.length) items.push({ label: `${s.title}: rows`, value: s.rows.length.toLocaleString('en-IN') })
    return items
  })
  if (b.summary && figures.length) {
    for (let i = 0; i < figures.length; i += 12) {
      const slide = pptx.addSlide()
      slide.addText(i ? 'Summary (cont.)' : 'Summary', { x: 0.5, y: 0.3, w: 12.3, h: 0.6, fontSize: 24, bold: true, color: INK })
      const chunk = figures.slice(i, i + 12)
      slide.addTable(
        chunk.map((f, k) => [
          { text: f.label, options: { color: MUTED, fill: { color: k % 2 ? 'F8FAFC' : 'FFFFFF' } } },
          { text: f.value, options: { bold: true, align: 'right', color: INK, fill: { color: k % 2 ? 'F8FAFC' : 'FFFFFF' } } },
        ]),
        { x: 0.5, y: 1.1, w: 12.3, colW: [7.3, 5.0], fontSize: 14, border: { type: 'solid', pt: 0.5, color: 'E2E8F0' } }
      )
      if (footer) slide.addText(footer, { x: 0.5, y: 7.0, w: 12.3, h: 0.3, fontSize: 9, color: MUTED })
    }
  }

  for (const s of sections) {
    const total = s.columns.reduce((n, c) => n + (c.width ?? 1), 0) || 1
    const colW = s.columns.map(c => ((c.width ?? 1) / total) * 12.3)
    const fontSize = s.columns.length > 10 ? 7 : s.columns.length > 7 ? 8 : 10
    const head = s.columns.map(c => ({ text: c.label, options: { bold: true, color: 'FFFFFF', fill: { color: HEAD_BG }, align: alignOf(c.type) } }))
    const cell = (c: ExportColumn, v: unknown, extra: Record<string, unknown> = {}) => ({ text: displayText(v, c.type), options: { align: alignOf(c.type), color: INK, ...extra } })
    const pages = Math.max(1, Math.ceil(s.rows.length / ROWS_PER_SLIDE))
    for (let p = 0; p < pages; p++) {
      const slide = pptx.addSlide()
      const chunk = s.rows.slice(p * ROWS_PER_SLIDE, (p + 1) * ROWS_PER_SLIDE)
      const range = s.rows.length ? ` · rows ${p * ROWS_PER_SLIDE + 1}–${p * ROWS_PER_SLIDE + chunk.length} of ${s.rows.length.toLocaleString('en-IN')}` : ''
      slide.addText(`${s.title}${range}`, { x: 0.5, y: 0.25, w: 12.3, h: 0.5, fontSize: 18, bold: true, color: INK })
      const body = chunk.map((r, k) => s.columns.map(c => cell(c, r[c.key], k % 2 ? { fill: { color: 'F8FAFC' } } : {})))
      if (!chunk.length) body.push(s.columns.map((c, i) => cell(c, i === 0 ? 'No rows' : '')))
      if (p === pages - 1 && s.totals) {
        const labelKey = totalsLabelKey(s.columns, s.totals)
        body.push(s.columns.map(c => cell(c, c.key === labelKey ? 'Total' : s.totals![c.key], { bold: true, fill: { color: 'EEF2FF' } })))
      }
      slide.addTable([head, ...body], { x: 0.5, y: 0.85, w: 12.3, colW, fontSize, border: { type: 'solid', pt: 0.5, color: 'E2E8F0' }, valign: 'middle' })
      if (footer) slide.addText(footer, { x: 0.5, y: 7.0, w: 9, h: 0.3, fontSize: 9, color: MUTED })
      if (b.pageNumbers) slide.addText(String(p + 1), { x: 11.8, y: 7.0, w: 1.0, h: 0.3, fontSize: 9, color: MUTED, align: 'right' })
    }
  }

  const note = truncationNote(doc)
  if (note) {
    const slide = pptx.addSlide()
    slide.addText(note, { x: 0.5, y: 3.0, w: 12.3, h: 1.0, fontSize: 16, color: 'B45309', align: 'center' })
  }

  // 'STREAM' is the output type that honours compression (a Node buffer, DEFLATE).
  const buf: Buffer = await pptx.write({ outputType: 'STREAM', compression: true })
  const bytes = new Uint8Array(buf)
  const body = new ReadableStream<Uint8Array>({
    start(c) {
      c.enqueue(bytes)
      c.close()
    },
  })
  return { body, contentType: CONTENT_TYPES.pptx }
}
