/** Default column order: identifying columns first, then the rest, optional ones left out. */
export function defaultColumns(columns: ExportColumn[]): string[] {
  const on = columns.filter(c => !c.optional)
  return [...on.filter(c => c.id), ...on.filter(c => !c.id)].map(c => c.key)
}

export function defaultFilterValues(filters: ExportFilter[]): FilterValues {
  const out: FilterValues = {}
  for (const f of filters) {
    if (f.kind === 'toggle') out[f.key] = f.default === true
    else out[f.key] = Array.isArray(f.default) ? [...f.default] : (f.options ?? []).map(o => o.value)
  }
  return out
}

export function defaultOptions(schema: Pick<ExportSchema, 'columns' | 'filters' | 'scopes' | 'formats'> & { range?: DateRange }): ExportOptions {
  return {
    format: schema.formats.includes('xlsx') ? 'xlsx' : schema.formats[0],
    scope: schema.scopes.includes('filtered') ? 'filtered' : schema.scopes[0],
    columns: defaultColumns(schema.columns),
    filters: defaultFilterValues(schema.filters),
    range: schema.range,
    branding: { ...DEFAULT_BRANDING },
  }
}

const DAY = /^\d{4}-\d{2}-\d{2}$/

/**
 * Options clamped to what the schema allows: unknown columns, filter values, formats and scopes are
 * dropped or replaced by the defaults. Used by the dialog (applying a preset made against an older
 * schema) and by the server (never trusting the body).
 */
export function sanitizeOptions(
  schema: Pick<ExportSchema, 'columns' | 'filters' | 'scopes' | 'formats'> & { dateRange?: ExportSchema['dateRange'] },
  raw: Partial<ExportOptions> | null | undefined
): ExportOptions {
  const d = defaultOptions(schema)
  const r = raw ?? {}
  const format = schema.formats.includes(r.format as ExportFormat) ? (r.format as ExportFormat) : d.format
  const scope = schema.scopes.includes(r.scope as ExportScope) ? (r.scope as ExportScope) : d.scope
  const known = new Set(schema.columns.map(c => c.key))
  const cols = Array.isArray(r.columns) ? [...new Set(r.columns.filter(k => typeof k === 'string' && known.has(k)))] : []
  const filters: FilterValues = {}
  for (const f of schema.filters) {
    const v = r.filters?.[f.key]
    if (f.kind === 'toggle') filters[f.key] = typeof v === 'boolean' ? v : d.filters[f.key]
    else {
      const allowed = new Set((f.options ?? []).map(o => o.value))
      filters[f.key] = Array.isArray(v) ? v.filter(x => typeof x === 'string' && allowed.has(x)) : d.filters[f.key]
    }
  }
  const branding = { ...DEFAULT_BRANDING }
  for (const k of Object.keys(branding) as (keyof BrandingOptions)[]) {
    const v = r.branding?.[k]
    if (typeof v === 'boolean') branding[k] = v
  }
  const range: DateRange = {}
  if (schema.dateRange && r.range) {
    if (typeof r.range.from === 'string' && DAY.test(r.range.from)) range.from = r.range.from
    if (typeof r.range.to === 'string' && DAY.test(r.range.to)) range.to = r.range.to
  }
  return { format, scope, columns: cols.length ? cols : d.columns, filters, range: range.from || range.to ? range : undefined, branding }
}

/** "Channel: Online, Cash sale" lines for the filters a user narrowed (all-ticked multis are no filter). */
export function describeFilterValues(filters: ExportFilter[], values: FilterValues): string[] {
  const out: string[] = []
  for (const f of filters) {
    const v = values[f.key]
    if (f.kind === 'toggle') {
      if (v === true) out.push(f.label)
      continue
    }
    const opts = f.options ?? []
    const picked = Array.isArray(v) ? v : []
    if (picked.length >= opts.length) continue
    const labels = opts.filter(o => picked.includes(o.value)).map(o => o.label)
    out.push(`${f.label}: ${labels.length ? labels.join(', ') : 'none'}`)
  }
  return out
}

/** Multi values a user narrowed, or null when every option is ticked (no constraint). */
export function narrowed(filter: ExportFilter | undefined, values: FilterValues): string[] | null {
  if (!filter || filter.kind !== 'multi') return null
  const v = values[filter.key]
  const picked = Array.isArray(v) ? v : []
  return picked.length >= (filter.options?.length ?? 0) ? null : picked
}

/** `base-YYYY-MM-DD.ext`; pass day null when the base already names its period. */
export function exportFilename(base: string, format: ExportFormat, day: string | null = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' })): string {
  const safe = base.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '') || 'export'
  return day ? `${safe}-${day}.${FORMAT_EXT[format]}` : `${safe}.${FORMAT_EXT[format]}`
}
