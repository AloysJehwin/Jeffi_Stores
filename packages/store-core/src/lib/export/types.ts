// Shared export contract (client-safe): what a page's export definition declares, what the dialog
// sends back, and the defaults both sides derive from it. The server re-validates everything.

export const EXPORT_FORMATS = ['csv', 'xlsx', 'pdf', 'pptx'] as const
export type ExportFormat = (typeof EXPORT_FORMATS)[number]

export const FORMAT_LABELS: Record<ExportFormat, string> = { csv: 'CSV', xlsx: 'Excel', pdf: 'PDF', pptx: 'PowerPoint' }
export const FORMAT_EXT: Record<ExportFormat, string> = { csv: 'csv', xlsx: 'xlsx', pdf: 'pdf', pptx: 'pptx' }

