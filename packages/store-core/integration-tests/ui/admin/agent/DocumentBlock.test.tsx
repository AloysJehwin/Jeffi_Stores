import { describe, it, expect, vi } from 'vitest'
import { render, screen, fireEvent, within } from '@testing-library/react'

vi.mock('next/link', () => ({ default: ({ href, children, ...r }: any) => <a href={href} {...r}>{children}</a> }))

import DocumentBlock, { type DocumentBlockData, type DocumentLine } from '@/components/admin/agent/DocumentBlock'

const line = (i: number, o: Partial<DocumentLine> = {}): DocumentLine => ({ name: `Item ${i}`, qty: 2, unit: 'pcs', rate: 100, amount: 200, ...o })

const doc = (o: Partial<DocumentBlockData> = {}): DocumentBlockData => ({
  type: 'document',
  kind: 'quotation',
  title: 'QT-001',
  subtitle: 'Valid 7 days',
  status: { label: 'Draft', tone: 'warn' },
  parties: [{ label: 'Bill to', name: 'Acme Ltd', lines: ['Pune', 'GSTIN 27AAA'] }],
  meta: [{ key: 'Date', value: '1 Jan 2026' }],
  lines: [line(1, { sku: 'SKU1', variant: 'Red', discountPct: 10, taxPct: 18, rateNote: 'per pc', baseQty: '= 50 pcs', href: '/admin/products/1' }), line(2, { warning: 'Low stock' })],
  totals: [
    { key: 'Subtotal', value: 400 },
    { key: 'Total', value: 472, emphasis: true },
  ],
  notes: 'Pay in 7 days',
  footnote: 'Generated by agent',
  ...o,
})

describe('DocumentBlock', () => {
  it('shows kind, title, subtitle and status', () => {
    render(<DocumentBlock block={doc()} />)
    expect(screen.getByText('Quotation')).toBeInTheDocument()
    expect(screen.getByText('QT-001')).toBeInTheDocument()
    expect(screen.getByText('Valid 7 days')).toBeInTheDocument()
    expect(screen.getByText('Draft')).toBeInTheDocument()
  })

  it('hides the kind label when it equals the title', () => {
    render(<DocumentBlock block={doc({ kind: 'invoice', title: 'Invoice' })} />)
    expect(screen.getAllByText('Invoice')).toHaveLength(1)
  })

  it('renders parties and meta', () => {
    render(<DocumentBlock block={doc()} />)
    expect(screen.getByText('Bill to')).toBeInTheDocument()
    expect(screen.getByText('Acme Ltd')).toBeInTheDocument()
    expect(screen.getByText('GSTIN 27AAA')).toBeInTheDocument()
    expect(screen.getByText('Date')).toBeInTheDocument()
    expect(screen.getByText('1 Jan 2026')).toBeInTheDocument()
  })

  it('renders line details: quantity, base qty, rate, discount and tax badges, variant and SKU, warning, link', () => {
    render(<DocumentBlock block={doc()} />)
    expect(screen.getByText('2 items')).toBeInTheDocument()
    const first = screen.getAllByRole('listitem')[0]
    expect(within(first).getByRole('link', { name: 'Item 1' })).toHaveAttribute('href', '/admin/products/1')
    expect(first).toHaveTextContent('2 pcs = 50 pcs × ₹100.00/pc')
    expect(within(first).getByText('10% off')).toBeInTheDocument()
    expect(within(first).getByText('GST 18%')).toBeInTheDocument()
    expect(first).toHaveTextContent('Red · SKU1')
    expect(screen.getByText('Low stock')).toBeInTheDocument()
    expect(screen.getAllByText('₹200.00')).toHaveLength(2)
  })

  it('singular item count and no-link plain name', () => {
    render(<DocumentBlock block={doc({ lines: [line(1)] })} />)
    expect(screen.getByText('1 item')).toBeInTheDocument()
    expect(screen.getByText('Item 1').closest('a')).toBeNull()
  })

  it('shows totals with emphasis, notes and footnote', () => {
    render(<DocumentBlock block={doc()} />)
    expect(screen.getByText('Subtotal')).toBeInTheDocument()
    expect(screen.getByText('₹400.00')).toBeInTheDocument()
    expect(screen.getByText('₹472.00')).toHaveClass('font-bold')
    expect(screen.getByText('Pay in 7 days')).toBeInTheDocument()
    expect(screen.getByText('Generated by agent')).toBeInTheDocument()
  })

  it('collapses a long list and expands with the toggle', () => {
    const lines = Array.from({ length: 12 }, (_, i) => line(i + 1))
    render(<DocumentBlock block={doc({ lines })} />)
    expect(screen.getAllByRole('listitem')).toHaveLength(6)
    fireEvent.click(screen.getByRole('button', { name: 'Show all 12 items' }))
    expect(screen.getAllByRole('listitem')).toHaveLength(12)
    fireEvent.click(screen.getByRole('button', { name: 'Show fewer' }))
    expect(screen.getAllByRole('listitem')).toHaveLength(6)
  })

  it('does not collapse at the threshold', () => {
    render(<DocumentBlock block={doc({ lines: Array.from({ length: 8 }, (_, i) => line(i + 1)) })} />)
    expect(screen.getAllByRole('listitem')).toHaveLength(8)
    expect(screen.queryByRole('button')).toBeNull()
  })

  it('tolerates missing optional parts', () => {
    render(<DocumentBlock block={{ type: 'document', kind: 'order', title: 'Order 5' } as any} />)
    expect(screen.getByText('Order 5')).toBeInTheDocument()
    expect(screen.queryByText('Amount')).toBeNull()
  })
})
