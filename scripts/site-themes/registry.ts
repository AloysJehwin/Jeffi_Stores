import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

// The generated index modules that ship the theme JSON (static imports, so every Next server bundle carries them).

export const THEMES_DIR = path.resolve(__dirname, '../../packages/store-core/src/lib/site/themes')
export const TEMPLATES_DIR = path.join(THEMES_DIR, 'templates')
export const SAMPLES_DIR = path.join(THEMES_DIR, 'samples')

const ident = (prefix: string, name: string) => `${prefix}_${name.replace(/[^A-Za-z0-9]/g, '_')}`
const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`)
const jsonFiles = (dir: string) =>
  readdirSync(dir)
    .filter(f => f.endsWith('.json'))
    .sort()

/** templates/index.ts from the JSON files in templates/ (`<style>.json` for stores, `showcase-<style>.json`). */
export function writeTemplateIndex(): void {
  const files = jsonFiles(TEMPLATES_DIR)
  const entries = files.map(f => {
    const base = f.slice(0, -5)
    const showcase = base.startsWith('showcase-')
    const style = showcase ? base.slice('showcase-'.length) : base
    return { f, style, showcase, id: ident(showcase ? 'showcase' : 'store', style) }
  })
  const list = (showcase: boolean) =>
    entries
      .filter(e => e.showcase === showcase)
      .map(e => `  ${key(e.style)}: ${e.id},`)
      .join('\n')
  writeFileSync(
    path.join(TEMPLATES_DIR, 'index.ts'),
    `// Generated by scripts/site-themes/generate-templates.ts from the JSON files beside it; do not edit. A style missing
// here has no pages yet, so its themes are offered as not ready.
${entries.map(e => `import ${e.id} from './${e.f}'\n`).join('')}
export const STORE_TEMPLATES: Record<string, unknown> = {${entries.some(e => !e.showcase) ? `\n${list(false)}\n` : ''}}

export const SHOWCASE_TEMPLATES: Record<string, unknown> = {${entries.some(e => e.showcase) ? `\n${list(true)}\n` : ''}}
`
  )
}

/** samples/index.ts from the JSON files in samples/ (one per selling category, by slug). */
export function writeSampleIndex(): void {
  const files = jsonFiles(SAMPLES_DIR)
  const entries = files.map(f => ({ f, slug: f.slice(0, -5), id: ident('sample', f.slice(0, -5)) }))
  writeFileSync(
    path.join(SAMPLES_DIR, 'index.ts'),
    `// Generated by scripts/site-themes/generate-samples.ts from the JSON files beside it (one per selling category, by
// slug); do not edit. A category missing here previews with the fallback sample (themes/sample.ts).
${entries.map(e => `import ${e.id} from './${e.f}'\n`).join('')}
export const SAMPLE_CATALOGS: Record<string, unknown> = {${entries.length ? `\n${entries.map(e => `  ${key(e.slug)}: ${e.id},`).join('\n')}\n` : ''}}
`
  )
}

/** `--name=value` (or a bare `--name`, as ''). */
export function arg(name: string): string | undefined {
  const hit = process.argv.find(a => a === `--${name}` || a.startsWith(`--${name}=`))
  if (!hit) return undefined
  return hit.includes('=') ? hit.split('=').slice(1).join('=') : ''
}

/** Loads the env as the other scripts do: the local overrides first, then .env.local and .env. */
export async function loadEnv(): Promise<void> {
  const { config } = await import('dotenv')
  for (const f of ['.env.local.overrides', '.env.local', '.env']) config({ path: path.resolve(__dirname, '../..', f) })
}
