// Pixabay photo search: GET https://pixabay.com/api/?key=…&q=…&image_type=photo&safesearch=true
// Terms (pixabay.com/api/docs): copy files to your own storage (no hotlinking), cache results 24 h, sizes over
// 1280 px need approval, so only largeImageURL (longest edge 1280) is used. AI-generated uploads are allowed there
// when labelled; those hits are dropped.

import type { StockImage, StockOrientation, StockProvider, StockQuery } from './types'
import { fetchJson } from './types'

const BASE = 'https://pixabay.com/api/'
const MAX_EDGE = 1280

interface PixabayHit {
  id?: number
  pageURL?: string
  type?: string
  tags?: string
  largeImageURL?: string
  imageWidth?: number
  imageHeight?: number
  user_id?: number
  user?: string
  isAiGenerated?: boolean
}

const ORIENTATION: Record<StockOrientation, string> = { landscape: 'horizontal', portrait: 'vertical', square: 'all' }
const AI_TAG = /\b(ai[\s-]?generated|generated by ai|ai art|ai image|midjourney|stable diffusion|dall-?e)\b/i

export function parsePixabay(json: unknown): StockImage[] {
  const hits = (json as { hits?: PixabayHit[] } | null)?.hits
  if (!Array.isArray(hits)) return []
  const out: StockImage[] = []
  for (const h of hits) {
    if (!h?.id || !h.largeImageURL || !h.pageURL || !h.imageWidth || !h.imageHeight) continue
    if ((h.type && h.type !== 'photo') || h.isAiGenerated || AI_TAG.test(h.tags ?? '')) continue
    const scale = Math.min(1, MAX_EDGE / Math.max(h.imageWidth, h.imageHeight))
    const user = (h.user ?? '').trim()
    out.push({
      provider: 'pixabay',
      id: String(h.id),
      url: h.largeImageURL,
      width: Math.round(h.imageWidth * scale),
      height: Math.round(h.imageHeight * scale),
      alt: (h.tags ?? '').split(',').map(t => t.trim()).filter(Boolean).slice(0, 4).join(', '),
      photographer: user || 'Pixabay',
      photographerUrl: user && h.user_id ? `https://pixabay.com/users/${encodeURIComponent(user)}-${h.user_id}/` : null,
      pageUrl: h.pageURL,
    })
  }
  return out
}

export class PixabayProvider implements StockProvider {
  readonly name = 'pixabay' as const
  constructor(
    private readonly key = process.env.PIXABAY_API_KEY || '',
    private readonly timeoutMs = Number(process.env.STOCK_TIMEOUT_MS) || 15_000,
  ) {}

  configured(): boolean { return !!this.key }

  async search(q: StockQuery): Promise<StockImage[]> {
    const params = new URLSearchParams({
      key: this.key,
      q: q.query.slice(0, 100),
      image_type: 'photo',
      safesearch: 'true',
      orientation: ORIENTATION[q.orientation],
      per_page: String(Math.max(3, Math.min(200, q.perPage))),
    })
    return parsePixabay(await fetchJson('pixabay', `${BASE}?${params}`, { timeoutMs: this.timeoutMs }))
  }
}

export const pixabayProvider = new PixabayProvider()
