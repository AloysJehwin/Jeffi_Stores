// Email bodies are HTML in the house style below, with {{var}} tokens. Only use a template's own tokens
// and the store/customer ones (a send with an unfilled token fails); test/catalog.test.ts checks it.

import type { UpsertInput } from '../src/templates-v2.js'
import campaignCatalog from './campaign-catalog.json' with { type: 'json' }

export type TemplateSeed = Omit<UpsertInput, 'publish'> & { tags?: string[] }

// Short helpers to keep the catalog readable.
const email = (slug: string, name: string, category: string, subject: string, preheader: string, body: string, tags?: string[]): TemplateSeed =>
  ({ slug, channel: 'email', name, category, subject, preheader, body, blocks_format: 'tiptap-html', tags })

// Email house style: greeting, headline, short paragraphs, a facts box, one button, sign-off. Inline
// styles survive the editor; the classes give buttons and boxes the store's accent until an edit drops them.
const BTN = 'display:inline-block;background:#2563eb;color:#ffffff;text-decoration:none;padding:12px 28px;border-radius:6px;font-weight:600;font-size:15px;'
const mail = (...parts: string[]) => parts.join('\n')
const hi = () => '<p>Hi {{customer_first_name}},</p>'
const h = (t: string) => `<h2>${t}</h2>`
const p = (t: string) => `<p>${t}</p>`
const list = (...items: string[]) => `<ul>${items.map(i => `<li>${i}</li>`).join('')}</ul>`
const facts = (...rows: [string, string][]) =>
  `<p class="info" style="background-color:#f0f9ff;border-left:4px solid #2563eb;padding:12px 16px;border-radius:4px;">${rows.map(([k, v]) => `<strong>${k}:</strong> ${v}`).join('<br>')}</p>`
const warn = (t: string) => `<p style="background-color:#fef3c7;border-left:4px solid #f59e0b;padding:12px 16px;border-radius:4px;">${t}</p>`
const code = (c: string) => `<p style="font-size:26px;font-weight:bold;letter-spacing:6px;text-align:center;background-color:#f3f4f6;padding:16px;border-radius:8px;">${c}</p>`
const button = (label: string, url: string) => `<p style="text-align:center;margin:28px 0;"><a class="button" href="${url}" style="${BTN}">${label}</a></p>`
const bye = (line = 'Warm regards') => `<p>${line},<br>Team {{store_name}}</p>`
/** Offered on the order page for one of its scenarios (controller lib/messaging/placements). */
const order = (scenario: string) => ['page:order', `scenario:order.${scenario}`]

/** Order details the order page fills in for its templates, on top of the store and customer ones. */
