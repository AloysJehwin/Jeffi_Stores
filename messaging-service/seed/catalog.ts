// Default platform template catalog. Copied per tenant on provisioning via
// POST /system-templates/install. Edits here do NOT retroactively touch existing
// tenants — a separate "Re-sync defaults" admin action handles that.
//
// Bodies here are plain-text with {{var}} tokens. The admin editor replaces each
// email seed with a Tiptap doc on first edit (stored in `blocks`, `blocks_format='tiptap'`).

import type { UpsertInput } from '../src/templates-v2.js'

export type TemplateSeed = Omit<UpsertInput, 'publish'> & { tags?: string[] }

// Short helpers to keep the catalog readable.
const email = (slug: string, name: string, category: string, subject: string, body: string, tags?: string[]): TemplateSeed =>
  ({ slug, channel: 'email', name, category, subject, body, blocks_format: 'tiptap', tags })

const sms = (slug: string, name: string, category: string, body: string, tags?: string[]): TemplateSeed =>
  ({ slug, channel: 'sms', name, category, body, blocks_format: 'sms-text', tags })

const wa = (slug: string, name: string, category: string, body: string, metaCategory: 'MARKETING' | 'UTILITY' | 'AUTHENTICATION', tags?: string[]): TemplateSeed =>
  ({ slug, channel: 'whatsapp', name, category, body, meta_category: metaCategory, blocks_format: 'wa-content', blocks: { types: { 'twilio/text': { body } } }, tags })

