// Run: npx tsx deploy/k8s/gen-routes.ts   (controller-service/tests/lib/k8s fails if the file drifts)
// The platform's IngressRoutes, from the routing table in packages/store-core/src/lib/service-routing.ts:
// jeffistores.in and its platform subdomains, and the catch-all for hosts no store namespace claims.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { AppName } from '../../packages/store-core/src/lib/service-routing'
import { EDGE_NS, hostMatch, PRIORITY_BAND, trafficRoutes, type HostGroup } from '../../packages/store-core/src/lib/k8s/traefik-routes'

export const ROUTES_PATH = join(__dirname, 'platform', '49-routes.yaml')
const ROOT = 'jeffistores.in'
const NS = 'jeffi'
const re = (s: string) => s.replace(/\./g, '\\.')

const backends = Object.fromEntries(
  (['controller', 'storefront', 'admin', 'business'] as AppName[]).map(app => [app, { name: `jeffi-stores-${app}-service`, port: 3000 }])
) as Record<AppName, { name: string; port: number }>
const strip = { name: 'strip-client-cert', namespace: EDGE_NS }

const INGRESS: { name: string; entryPoints: string[]; groups: HostGroup[]; middlewares?: { name: string; namespace: string }[]; band: number; tls?: object }[] = [
  {
    // CloudFront reaches the apex over plain HTTP; it terminates TLS itself.
    name: 'jeffi-stores-cloudfront-origin',
    entryPoints: ['web'],
    groups: [{ classes: ['store'], match: hostMatch([ROOT, `www.${ROOT}`]) }],
    band: PRIORITY_BAND.named,
  },
  {
    name: 'jeffi-stores',
    entryPoints: ['websecure'],
    groups: [
      { classes: ['store'], match: hostMatch([ROOT, `www.${ROOT}`, `forms.${ROOT}`, `vault.${ROOT}`]) },
      { classes: ['business'], match: hostMatch([`business.${ROOT}`]) },
      { classes: ['console'], match: hostMatch([`certificate.${ROOT}`, `ecom.${ROOT}`]) },
    ],
    middlewares: [strip],
    band: PRIORITY_BAND.named,
    // No options: the TLSOption named `default` applies automatically (naming it is an error).
    tls: {},
  },
  {
    name: 'jeffi-stores-admin',
    entryPoints: ['websecure'],
    groups: [{ classes: ['platform-admin', 'admin'], match: hostMatch([`admin.${ROOT}`]) }],
    middlewares: [strip, { name: 'pass-client-cert', namespace: EDGE_NS }],
    band: PRIORITY_BAND.named,
    tls: { options: { name: 'platform-mtls', namespace: EDGE_NS } },
  },
  {
    // Hosts not claimed by a store namespace or a service route: the flagship's pods answer, and 404 unknown stores.
    name: 'jeffi-stores-catch-all',
    entryPoints: ['websecure'],
    groups: [
      { classes: ['admin'], match: `HostRegexp(\`^admin-[a-z0-9-]+\\.${re(ROOT)}$\`)` },
      { classes: ['business'], match: `HostRegexp(\`^[a-z0-9-]+\\.business\\.${re(ROOT)}$\`)` },
      { classes: ['store'], match: `HostRegexp(\`^[a-z0-9-]+\\.${re(ROOT)}$\`)` },
    ],
    middlewares: [strip],
    band: PRIORITY_BAND.catchAll,
    tls: {},
  },
]

export function platformIngressRoutes() {
  return INGRESS.map(i => ({
    apiVersion: 'traefik.io/v1alpha1',
    kind: 'IngressRoute',
    metadata: { name: i.name, namespace: NS, labels: { 'jeffi.io/routes': 'platform' } },
    spec: {
      entryPoints: i.entryPoints,
      routes: trafficRoutes({ groups: i.groups, backends, middlewares: i.middlewares, band: i.band }),
      ...(i.tls ? { tls: i.tls } : {}),
    },
  }))
}

export function renderPlatformRoutes(): string {
  const docs = platformIngressRoutes().map(o =>
    [
      `apiVersion: ${o.apiVersion}`,
      `kind: ${o.kind}`,
      `metadata: ${JSON.stringify(o.metadata)}`,
      'spec:',
      `  entryPoints: ${JSON.stringify(o.spec.entryPoints)}`,
      '  routes:',
      ...o.spec.routes.map(r => `    - ${JSON.stringify(r)}`),
      ...(o.spec.tls ? [`  tls: ${JSON.stringify(o.spec.tls)}`] : []),
    ].join('\n')
  )
  const header =
    '# GENERATED by deploy/k8s/gen-routes.ts from packages/store-core/src/lib/service-routing.ts — do not edit.\n' +
    '# rollout.sh applies these (label jeffi.io/routes=platform) once the Deployments they point at are ready.\n'
  return header + docs.join('\n---\n') + '\n'
}

if (process.argv.some(a => a.endsWith('gen-routes.ts'))) {
  writeFileSync(ROUTES_PATH, renderPlatformRoutes())
  console.log(`wrote ${ROUTES_PATH}`)
}
