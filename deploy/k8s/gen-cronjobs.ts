// Renders deploy/k8s/platform/cronjobs.yaml from the CRON_JOBS registry.
// Run: npx jiti deploy/k8s/gen-cronjobs.ts   (tests/lib/k8s fails if the file drifts)
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CRON_JOBS, cronSchedule, type CronJob } from '../../src/lib/shared/cron-jobs'

export const CRONJOBS_PATH = join(__dirname, 'platform', 'cronjobs.yaml')

const k8sName = (id: string) => `cron-${id.replace(/_/g, '-')}`

function render(job: CronJob, extra?: { id: string; method: string; path: string; schedule: string }): string {
  const id = extra?.id ?? job.id
  const method = extra?.method ?? job.method
  const path = extra?.path ?? job.path
  const schedule = extra?.schedule ?? cronSchedule(job)
  const deadline = Math.max(50, Math.round((job?.lockTtlMs ?? 300_000) / 1000))
  return `apiVersion: batch/v1
kind: CronJob
metadata:
  name: ${k8sName(id)}
  namespace: jeffi
  labels: { app.kubernetes.io/part-of: jeffi-cron }
spec:
  schedule: '${schedule}'
  timeZone: Asia/Kolkata
  concurrencyPolicy: Forbid
  startingDeadlineSeconds: 120
  successfulJobsHistoryLimit: 1
  failedJobsHistoryLimit: 3
  jobTemplate:
    spec:
      backoffLimit: 0
      activeDeadlineSeconds: ${Math.min(deadline, 3000)}
      ttlSecondsAfterFinished: 600
      template:
        metadata:
          labels: { app.kubernetes.io/part-of: jeffi-cron }
        spec:
          restartPolicy: Never
          nodeSelector: { jeffi.io/role: core }
          imagePullSecrets: [{ name: regcred }]
          containers:
            - name: run
              image: 708835965056.dkr.ecr.us-east-1.amazonaws.com/jeffi-stores:latest
              # sleep: images before the retry in k8s-cron.mjs drop the first connection (netpol race)
              command: [sh, -c, 'sleep 3 && exec node deploy/k8s-cron.mjs ${id} ${method} ${path}']
              env:
                - name: CRON_SECRET
                  valueFrom: { secretKeyRef: { name: cron-secret, key: CRON_SECRET } }
              resources:
                requests: { cpu: 10m, memory: 48Mi }
                limits: { memory: 128Mi }
`
}

// Nightly feed syncs previously installed as a host crontab (deploy/sync-cron-setup.sh).
const FEED_SYNCS = [
  { id: 'merchant_sync', method: 'GET', path: '/api/admin/merchant/sync', schedule: '15 23 * * *' },
  { id: 'amazon_sync', method: 'GET', path: '/api/admin/merchant/amazon/sync', schedule: '45 23 * * *' },
]

export function renderCronJobs(): string {
  const header = '# GENERATED by deploy/k8s/gen-cronjobs.ts from src/lib/shared/cron-jobs.ts — do not edit.\n'
  const docs = [...CRON_JOBS.map(j => render(j)), ...FEED_SYNCS.map(f => render(CRON_JOBS[0], f))]
  return header + docs.join('---\n')
}

if (process.argv.some(a => a.endsWith('gen-cronjobs.ts'))) {
  writeFileSync(CRONJOBS_PATH, renderCronJobs())
  console.log(`wrote ${CRONJOBS_PATH}`)
}
