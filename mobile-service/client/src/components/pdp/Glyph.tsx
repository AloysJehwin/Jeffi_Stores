// Icons coloured by a text-* className, like the web's `<svg stroke="currentColor" className="text-…">`.

type Base = { size?: number; strokeWidth?: number; style?: StyleProp<TextStyle> }

const colorOf = (style?: StyleProp<TextStyle>) => StyleSheet.flatten(style)?.color as string | undefined

/** One of the web's inline SVGs: outline (stroke) by default, `solid` for fill="currentColor" icons. */
function PathIcon({
  d,
  size = 24,
  strokeWidth = 2,
  viewBox = '0 0 24 24',
  solid = false,
  evenOdd = false,
  style,
}: Base & { d: string | string[]; viewBox?: string; solid?: boolean; evenOdd?: boolean }) {
  const color = colorOf(style)
  return (
    <Svg
      width={size}
      height={size}
      viewBox={viewBox}
      fill={solid ? color : 'none'}
      stroke={solid ? undefined : color}
      strokeWidth={solid ? 0 : strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {(Array.isArray(d) ? d : [d]).map((p, i) => (
        <Path key={i} d={p} fillRule={evenOdd ? 'evenodd' : undefined} clipRule={evenOdd ? 'evenodd' : undefined} />
      ))}
    </Svg>
  )
}

function LucideTinted({ icon: Icon, size = 24, strokeWidth = 2, style }: Base & { icon: LucideIcon }) {
  return <Icon size={size} strokeWidth={strokeWidth} color={colorOf(style)} />
}

